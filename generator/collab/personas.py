"""## 8. Eligibility Gate

Python проверяет формальные критерии продукта до ранжирования. Это не банковский скоринг и не прогноз одобрения. Проверка лишь исключает профили, которые явно не соответствуют заданным пользователем правилам.

Наличие карты Цифра банка учитывается как трение в `adoption_readiness`, но не исключает человека: он может сначала открыть дебетовую карту.

"""

def check_rule(persona: SyntheticPersona, rule: EligibilityRule) -> bool:
    actual = getattr(persona, rule.field)
    expected = rule.value

    if rule.operator == "eq":
        return actual == expected
    if rule.operator == "in":
        return actual in expected
    if rule.operator == "gte":
        return actual >= expected
    if rule.operator == "lte":
        return actual <= expected
    if rule.operator == "between":
        low, high = expected
        return low <= actual <= high
    if rule.operator == "truthy":
        return bool(actual)
    raise ValueError(f"Неизвестный operator: {rule.operator}")


def eligibility_report(product: Product, persona: SyntheticPersona) -> dict:
    checks = [
        {
            "rule_id": rule.rule_id,
            "description": rule.description,
            "passed": check_rule(persona, rule),
        }
        for rule in product.eligibility_rules
    ]
    return {
        "persona_id": persona.persona_id,
        "hard_eligible": all(item["passed"] for item in checks),
        "checks": checks,
        "has_required_card_now": persona.has_cifra_debit_or_salary_card,
    }


