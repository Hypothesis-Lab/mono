def generated_text_blob(hypothesis: HypothesisDraft) -> str:
    return " ".join([
        hypothesis.hypothesis_statement,
        hypothesis.headline,
        hypothesis.message_frame,
        hypothesis.cta,
        hypothesis.experiment_design,
        hypothesis.why_for_persona,
    ])


def extract_numeric_claims(text: str) -> set[str]:
    return set(re.findall(r"(?<![A-Za-zА-Яа-я_])\d[\d\s]*(?:[.,]\d+)?\s*%?", text))


def compact_number(token: str) -> str:
    return re.sub(r"\s+", "", token).replace(",", ".")


def validate_hypothesis_batch(
    product: Product,
    persona: SyntheticPersona,
    batch: HypothesisBatch,
):
    errors = []
    expected_ids = [
        f"{persona.persona_id}_hyp_01",
        f"{persona.persona_id}_hyp_02",
        f"{persona.persona_id}_hyp_03",
    ]
    actual_ids = [h.hypothesis_id for h in batch.hypotheses]
    if actual_ids != expected_ids:
        errors.append(f"Неверные hypothesis_id: {actual_ids}")

    if any(h.persona_id != persona.persona_id for h in batch.hypotheses):
        errors.append("В batch есть гипотеза другой персоны.")

    allowed_fact_ids = {f.fact_id for f in product.facts}
    allowed_channels = set(product.allowed_channels)
    allowed_numbers = {
        compact_number(token)
        for fact in product.facts
        for token in extract_numeric_claims(fact.text)
    }

    value_angles = [h.value_angle for h in batch.hypotheses]
    if len(set(value_angles)) != 3:
        errors.append("У трех гипотез должны быть разные value_angle.")

    normalized_headlines = [re.sub(r"\W+", " ", h.headline.lower()).strip() for h in batch.hypotheses]
    if len(set(normalized_headlines)) != 3:
        errors.append("Заголовки гипотез дублируются.")

    for h in batch.hypotheses:
        unknown_facts = set(h.selected_fact_ids) - allowed_fact_ids
        if unknown_facts:
            errors.append(f"{h.hypothesis_id}: неизвестные fact_id {sorted(unknown_facts)}")
        if h.channel not in allowed_channels:
            errors.append(f"{h.hypothesis_id}: запрещенный канал {h.channel}")

        text = generated_text_blob(h).lower()
        for phrase in product.forbidden_claims:
            if phrase.lower() in text:
                errors.append(f"{h.hypothesis_id}: запрещенная формулировка '{phrase}'")

        used_numbers = {compact_number(x) for x in extract_numeric_claims(text)}
        unknown_numbers = used_numbers - allowed_numbers
        if unknown_numbers:
            errors.append(
                f"{h.hypothesis_id}: числа без подтверждения в facts {sorted(unknown_numbers)}"
            )

        if "потому что" not in h.hypothesis_statement.lower():
            errors.append(f"{h.hypothesis_id}: нет части «потому что».")

    if errors:
        raise ValueError("Hypothesis Validator:\n- " + "\n- ".join(errors))


def generate_hypotheses_for_persona(
    product: Product,
    persona: SyntheticPersona,
    research: PersonaResearch,
    ranking_item: dict,
    max_batches: int = 3,
) -> HypothesisBatch:
    last_error = None
    for attempt in range(1, max_batches + 1):
        print(f"  batch {attempt}/{max_batches}")
        batch = run_llm_json(
            system_prompt=(
                "Ты создаешь проверяемые маркетинговые гипотезы на основе "
                "синтетического интервью и подтвержденных продуктовых фактов."
            ),
            user_prompt=build_hypothesis_prompt(product, persona, research, ranking_item),
            response_model=HypothesisBatch,
            temperature=0.35,
            max_new_tokens=2000,
        )
        try:
            validate_hypothesis_batch(product, persona, batch)
            return batch
        except Exception as exc:
            last_error = exc
            print("  batch отклонен:", exc)
    raise RuntimeError(
        f"Не удалось получить валидные гипотезы для {persona.persona_id}: {last_error}"
    )


def materialize_hypothesis(product: Product, draft: HypothesisDraft) -> dict:
    fact_map = {f.fact_id: f.text for f in product.facts}
    result = draft.model_dump()
    result["proof_points"] = [fact_map[fact_id] for fact_id in draft.selected_fact_ids]
    result["status"] = "synthetic_hypothesis_requires_real_validation"
    return result


def hypothesis_tokens(item: dict) -> set[str]:
    text = " ".join([
        item["hypothesis_statement"],
        item["headline"],
        item["message_frame"],
        item["why_for_persona"],
    ]).lower()
    return {
        token
        for token in re.findall(r"[a-zа-яё]{4,}", text)
        if token not in {"если", "потому", "который", "которая", "через", "этого"}
    }


def cross_persona_diversity_warnings(hypotheses_map: dict[str, list[dict]]) -> list[str]:
    items = [item for batch in hypotheses_map.values() for item in batch]
    warnings = []
    for index, left in enumerate(items):
        for right in items[index + 1:]:
            if left["persona_id"] == right["persona_id"]:
                continue
            left_tokens = hypothesis_tokens(left)
            right_tokens = hypothesis_tokens(right)
            union = left_tokens | right_tokens
            similarity = len(left_tokens & right_tokens) / len(union) if union else 0.0
            if similarity >= 0.80:
                warnings.append(
                    f'{left["hypothesis_id"]} и {right["hypothesis_id"]}: '
                    f'возможный смысловой дубль, Jaccard={similarity:.2f}'
                )
    return warnings


