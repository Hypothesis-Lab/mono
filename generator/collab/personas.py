"""## 10. Weighted Ranker на Python и выбор топ‑3

LLM не видит оценки других персон и не выбирает победителей. Код применяет фиксированные веса, исключает только формально неподходящие профили и возвращает ровно три персоны.

"""

def calculate_persona_score(scores: PersonaMetricScores) -> float:
    value = sum(
        getattr(scores, metric) * weight
        for metric, weight in PERSONA_SCORE_WEIGHTS.items()
    )
    return round(value, 2)


def rank_personas(
    personas: list[SyntheticPersona],
    scores: list[PersonaMetricScores],
    eligibility_map: dict[str, dict],
) -> list[dict]:
    persona_by_id = {p.persona_id: p for p in personas}
    rows = []

    for item in scores:
        eligibility_item = eligibility_map[item.persona_id]
        rows.append({
            "persona_id": item.persona_id,
            "label": persona_by_id[item.persona_id].label,
            "hard_eligible": eligibility_item["hard_eligible"],
            "has_required_card_now": eligibility_item["has_required_card_now"],
            "metrics": item.model_dump(),
            "weights": PERSONA_SCORE_WEIGHTS,
            "final_score": calculate_persona_score(item),
        })

    rows.sort(
        key=lambda x: (
            not x["hard_eligible"],
            -x["final_score"],
            x["persona_id"],
        )
    )

    eligible_rank = 0
    for row in rows:
        if row["hard_eligible"]:
            eligible_rank += 1
            row["rank"] = eligible_rank
        else:
            row["rank"] = None
    return rows


