"""## 3. Общая функция вызова LLM

Полная Pydantic Schema не передаётся модели: Qwen3‑4B иногда копирует `$defs`
вместо ответа. Модель получает только список верхнеуровневых полей, а конкретный
формат задаётся компактным примером в промпте каждого модуля.

Парсер:

- выделяет несколько JSON-объектов, если модель напечатала их подряд;
- проверяет каждый объект по Pydantic и пропускает случайно повторённую схему;
- исправляет небольшие синтаксические ошибки с помощью `json-repair`;
- при неудаче просит вернуть весь объект заново без Markdown и `$defs`.

"""

def split_json_object_fragments(text: str) -> list[str]:
    """Выделяет сбалансированные верхнеуровневые {...} с учетом строк."""
    fragments = []
    start = None
    depth = 0
    in_string = False
    escaped = False

    for index, char in enumerate(text):
        if in_string:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            continue

        if char == '"':
            in_string = True
        elif char == "{":
            if depth == 0:
                start = index
            depth += 1
        elif char == "}" and depth > 0:
            depth -= 1
            if depth == 0 and start is not None:
                fragments.append(text[start:index + 1])
                start = None

    return fragments


def extract_json_candidates(text: str) -> list[dict]:
    """Возвращает все похожие на ответ JSON-объекты, включая repaired."""
    cleaned = text.strip()
    cleaned = re.sub(r"```(?:json)?", "", cleaned, flags=re.IGNORECASE)
    fragments = split_json_object_fragments(cleaned)

    # Если объект оборван, json-repair иногда может восстановить весь хвост.
    if not fragments and "{" in cleaned:
        fragments = [cleaned[cleaned.find("{"):]]

    candidates = []
    seen = set()

    for fragment in fragments:
        parsed_variants = []
        try:
            parsed_variants.append(json.loads(fragment))
        except Exception:
            pass

        try:
            repaired = repair_json(fragment, return_objects=True)
            parsed_variants.append(repaired)
        except Exception:
            pass

        for item in parsed_variants:
            if not isinstance(item, dict):
                continue
            marker = json.dumps(item, ensure_ascii=False, sort_keys=True)
            if marker not in seen:
                seen.add(marker)
                candidates.append(item)

    return candidates


def run_llm_json(
    system_prompt: str,
    user_prompt: str,
    response_model,
    max_attempts: int = 3,
    temperature: float = 0.20,
    max_new_tokens: int = 1600,
):
    last_error = None
    retry_note = ""
    expected_fields = list(response_model.model_fields.keys())
    format_note = (
        "\n\nТЕХНИЧЕСКИЙ ФОРМАТ: верни ровно ОДИН JSON-объект без Markdown, "
        "пояснений и JSON Schema. Не возвращай ключи $defs, properties, title, "
        "required или type на верхнем уровне. Ожидаемые верхнеуровневые поля: "
        + ", ".join(expected_fields)
        + "."
    )

    for attempt in range(1, max_attempts + 1):
        messages = [
            {"role": "system", "content": system_prompt},
            {
                "role": "user",
                "content": (
                    user_prompt
                    + format_note
                    + retry_note
                ),
            },
        ]
        chat_text = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True,
            enable_thinking=False,
        )
        model_inputs = tokenizer([chat_text], return_tensors="pt").to(model.device)
        generated_ids = model.generate(
            **model_inputs,
            max_new_tokens=max_new_tokens,
            do_sample=True,
            temperature=temperature,
            top_p=0.8,
            top_k=20,
        )
        output_ids = generated_ids[0][model_inputs.input_ids.shape[-1]:]
        raw_text = tokenizer.decode(output_ids, skip_special_tokens=True).strip()

        try:
            candidates = extract_json_candidates(raw_text)
            if not candidates:
                raise ValueError("В ответе модели не найден JSON-объект.")

            candidate_errors = []
            for candidate in candidates:
                try:
                    return response_model.model_validate(candidate)
                except Exception as candidate_exc:
                    candidate_errors.append(candidate_exc)

            raise candidate_errors[-1]

        except Exception as exc:
            last_error = exc
            short_error = re.sub(r"\s+", " ", str(exc))[:500]
            retry_note = (
                "\n\nПРЕДЫДУЩИЙ ОТВЕТ НЕ ПРОШЕЛ ПРОВЕРКУ. "
                "Сформируй ВЕСЬ ответ заново как один JSON-объект. "
                "Не копируй схему и не продолжай предыдущий текст. "
                f"Краткая ошибка: {short_error}"
            )
            print(f"Попытка {attempt}: JSON не прошёл валидацию — {exc}")
        finally:
            del model_inputs, generated_ids, output_ids
            torch.cuda.empty_cache()

    raise RuntimeError(
        f"После {max_attempts} попыток не удалось получить валидный JSON. "
        f"Последняя ошибка: {last_error}"
    )

